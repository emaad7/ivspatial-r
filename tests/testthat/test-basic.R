test_that("size under independence and data-driven resolution", {
  g <- lattice_graph(10, 10)
  ref <- reference_table(g, B = 199, seed = 1)
  set.seed(1)
  p <- vapply(1:150, function(i) spatial_test(rt(100, 3), g, reference = ref, seed = i, features = FALSE,
                                              asymptotic = FALSE)$p_value, numeric(1))
  expect_true(mean(p <= 0.05) >= 0.01 && mean(p <= 0.10) <= 0.18)
  a <- spatial_test(mercer_hall$grain, lattice_graph(20, 25), B = 99, seed = 1, resolution = "auto")
  expect_true(is.character(a$selected))
  s <- spatial_test(mercer_hall$grain, lattice_graph(20, 25), B = 99, seed = 1, resolution = "schwarz", lags = 2)
  expect_equal(nrow(s$components), 20L)
})

