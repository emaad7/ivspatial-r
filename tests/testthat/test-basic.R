test_that("statistics agree with the Python package", {
  x <- log(baltimore$PRICE)
  r <- ranks_by_index(x)
  xy <- cbind(baltimore$X, baltimore$Y)
  stat <- function(gr, d, s) ivspatial:::tv_T(ivspatial:::tv_engine(gr, d, s), matrix((d * r) %/% gr$n))
  gk <- knn_graph(xy, 4)
  expect_equal(stat(gk, 4, 3), 1167.4123222749, tolerance = 1e-9)
  expect_equal(stat(gk, 4, 2), 656.8120063191, tolerance = 1e-9)
  expect_equal(stat(gk, 3, 2), 549.8827014218, tolerance = 1e-9)
  rm <- ivspatial:::rank_moran_stats(ivspatial:::rank_moran(gk), r)
  expect_equal(c(rm$RM, rm$RS), c(0.49913761534301637, 0.4649986417636346), tolerance = 1e-9)
  expect_equal(stat(lag_graph(gk, 2), 4, 3), 2066.309233060562, tolerance = 1e-9)
  skip_if_not_installed("deldir")
  gd <- delaunay_graph(xy)
  expect_equal(sum(gd$degree), 1236L)
  expect_equal(stat(gd, 4, 3), 1621.2462913468612, tolerance = 1e-9)
  expect_equal(stat(gd, 4, 2), 1036.8670380358672, tolerance = 1e-9)
})

test_that("exact covariance: diagonal and trace", {
  g <- lattice_graph(12, 12)
  eng <- ivspatial:::tv_engine(g, 4, 3)
  S <- ivspatial:::tv_sigma(eng)
  expect_true(isSymmetric(S))
  # simulated covariance of the features agrees with the exact one
  set.seed(1)
  R <- vapply(1:3000, function(i) sample.int(144) - 1L, integer(144))
  W <- ivspatial:::tv_W(eng, (4 * R) %/% 144)
  expect_lt(max(abs(stats::cov(t(W)) - S)), 0.2)
})

test_that("API and reproducibility", {
  g <- lattice_graph(20, 25)
  a <- spatial_test(mercer_hall$grain, g, B = 199, seed = 3)
  b <- spatial_test(mercer_hall$grain, g, B = 199, seed = 3)
  expect_identical(a$p_value, b$p_value)
  expect_true(a$reject)
  expect_equal(nrow(a$components), 4L)
  expect_s3_class(as.data.frame(a), "data.frame")
  expect_output(print(a), "C4 = min-P")
  expect_gt(a$features[["c.lin|n.lin"]], 5)
  s <- screen_variables(mercer_hall, g, columns = c("grain", "straw"), B = 99, seed = 1)
  expect_equal(nrow(s$table), 2L)
  lf <- local_features(mercer_hall$grain, g)
  expect_equal(dim(lf), c(500L, 15L))
  nl <- null_limit(g, 4, 2, 35)
  expect_equal(nl$p_value, 0.08585474635195689, tolerance = 1e-6)
  expect_equal(unname(nl$critical["0.05"]), 38.52705627198316, tolerance = 1e-6)
})

